/** Languages the interface is written in, with their own names. */
export const LANGUAGES = { en: "English", fr: "Français" } as const;

/** Looks up a string and fills its `{placeholders}`. */
export type Translate = (key: Key, values?: Record<string, string | number>) => string;

/** A `Translate` for a BCP‑47 language, falling back to English. */
export function translator(language: string, always: Record<string, string> = {}): Translate {
  const table = language.toLowerCase().startsWith("fr") ? fr : en;
  return (key, values) =>
    table[key].replace(/\{(\w+)\}/g, (_, name: string) => String(values?.[name] ?? always[name] ?? ""));
}

/** A readable name for an engine id (`claude` → "Claude"). */
export function engineName(provider: string): string {
  return provider.charAt(0).toUpperCase() + provider.slice(1);
}
