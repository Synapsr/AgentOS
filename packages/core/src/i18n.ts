/** A translator bound to one language: `t("doing.reading", { what: "notes.txt" })`. */
export type Translate = (key: Key, values?: Record<string, string | number>) => string;

/** Returns the translator for a BCP-47 language. Anything that is not French gets English. */
export function translator(language: string): Translate {
  const table = language.toLowerCase().startsWith("fr") ? fr : en;
  return (key, values = {}) => table[key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}
